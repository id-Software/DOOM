#!/usr/bin/env python3
"""Recreate the committed synthetic BLOCKMAP corner fixture byte for byte.

The scene is reconstructed from this branch's tests/reference/blockmap_corner.wad:
one 768-by-768 room, an 8-by-8 void pillar, and one player start. Geometry uses
the existing M4b void builder and M4a side textures; blank game data and WAD
framing follow m4b_wad.py and its frozen M3h9c helpers. No historical investigation
generator, commercial data, or existing fixture bytes are read during generation.

    blockmap_corner_wad.py --check
    blockmap_corner_wad.py --out /tmp/blockmap_corner.wad
    blockmap_corner_wad.py --west-control --out /tmp/blockmap_corner_west.wad

The west control changes only the player's THINGS x coordinate, from 308 to 307.
--check compares in memory with --out when given, otherwise the committed fixture;
it never writes. The west control requires --out and cannot replace the fixture.
"""

import argparse
import hashlib
import struct
import sys
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools/reference'))
import m4b_wad as B  # noqa: E402  existing synthetic geometry and frozen game data

WAD = ROOT / 'tests/reference/blockmap_corner.wad'


def wad_bytes(west_control=False):
    """Build S3, or its one-unit-west C10S control, without reading either WAD."""
    plan = B.Plan('blockmap_corner')
    room = plan.sector('ROOM', [(0, 0, 768, 768)])
    plan.void(room, 425, 444, 433, 452)
    plan.thing(307 if west_control else 308, 276, 45, B.PLAYER1)
    m = B.build_map(plan)
    B.A.fix_sides(plan, m)
    lumps = dict(m['lumps'])
    lumps['THINGS'] = b''.join(struct.pack('<hhhhh', *t) for t in plan.things)
    assert list(lumps) == ['MAP01'] + B.A.MAP_LUMPS, list(lumps)

    # Same ordered, blank resources and IWAD directory framing as m4b_wad.py.
    w = B.W
    wad = ([('PLAYPAL', w.playpal()), ('COLORMAP', w.colormap()),
            ('S_START', b''), ('S_END', b''), ('F_START', b'')] +
           [(f, bytes(4096)) for f in w.FLATS] +
           [('F_END', b''), ('PNAMES', w.pnames()), ('TEXTURE1', w.texture1()),
            (w.PATCH, w.blank_patch(w.TEX_W, w.TEX_H)), ('E1M1', b'')] +
           [(n, lumps[n]) for n in B.A.MAP_LUMPS])
    data = bytearray(b'IWAD' + struct.pack('<ii', len(wad), 0))
    directory = bytearray()
    for name, body in wad:
        directory += struct.pack('<ii8s', len(data), len(body), w.name8(name))
        data += body
    struct.pack_into('<i', data, 8, len(data))
    return bytes(data + directory), len(wad)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', type=Path, help='output or comparison path (default: committed S3 fixture)')
    ap.add_argument('--check', action='store_true', help='compare regenerated bytes without writing')
    ap.add_argument('--west-control', action='store_true', help='move the player one map unit west (C10S)')
    args = ap.parse_args()
    target = args.out if args.out is not None else WAD
    if args.west_control and (args.out is None or target.resolve() == WAD.resolve()):
        ap.error('--west-control requires --out pointing somewhere other than the committed fixture')
    data, count = wad_bytes(args.west_control)
    if args.check:
        if not target.is_file() or target.read_bytes() != data:
            sys.exit(f'{target} differs from the regenerated WAD')
        action = 'matches'
    else:
        target.write_bytes(data)
        action = 'written'
    print(f'{target} {action}: {len(data)} bytes, {count} lumps, '
          f'sha256 {hashlib.sha256(data).hexdigest()}')


if __name__ == '__main__':
    main()
