#!/usr/bin/env python3
"""Generator and checker of the two data files of crates/doom-sound (M5c, Phase 2 step 4).

  crates/doom-sound/src/sounds_table.rs  the 109-entry S_sfx table of linuxdoom-1.10, parsed from
                                         sounds.c:114-227 (initialisers: name, singularity, priority,
                                         link, pitch, volume, data) and paired with the sfxenum_t
                                         enumerators of sounds.h:177-289 (sfx_None = 0 ... NUMSFX = 109).
  crates/doom-sound/src/steptable.rs     steptable[256] of I_SetChannels (i_sound.c:404, 414-415):
                                         steptable[p] = (int)(pow(2.0, (p-128)/64.0) * 65536.0),
                                         computed here with no floating point as the integer 64th
                                         root of 2^(1024 + p - 128) (the product is positive and the
                                         multiplication by 65536 exact; margin to the nearest integer
                                         0.0125, M5c note section 3.2.6), with its SHA-256 over the
                                         little-endian int32 array checked against the genuine digest
                                         95f2209c...6dde recorded by the genuine mixer harness.

The table is checked, not trusted: every enumerator must pair with a table row (names match after
the "sfx_" prefix), exactly one row may be linked, and the link must name an existing enumerator.

    m5c_sounds_table.py            write both files
    m5c_sounds_table.py --check    compare both files with what would be written; write nothing;
                                   exit 1 on any difference
    m5c_sounds_table.py --self-test  run the --check comparison on planted faults (in memory; writes
                                   nothing): the committed text of each file must give "matches", the
                                   same text with one changed byte "DIFFERS", and a steptable with one
                                   changed entry must fail the genuine digest
    m5c_sounds_table.py --check --self-test   both, in that order
"""
import hashlib, re, struct, sys
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'linuxdoom-1.10'
OUT_TABLE = ROOT / 'crates/doom-sound/src/sounds_table.rs'
OUT_STEP = ROOT / 'crates/doom-sound/src/steptable.rs'
STEP_SHA256 = '95f2209c952180e797cf3ef5a836db333d8ca88fc3b1c7893f136272f4e96dde'   # tests/reference/m5c_mixer_results.json


def enumerators():
    text = (SRC / 'sounds.h').read_text(encoding='latin-1').splitlines()
    start = next(i for i, l in enumerate(text) if l.strip() == 'sfx_None,')
    names = []
    for i in range(start, len(text)):
        s = text[i].strip().rstrip(',')
        if s == 'NUMSFX':
            return names, start + 1, i + 1
        if not re.fullmatch(r'sfx_\w+', s):
            sys.exit(f'sounds.h:{i + 1}: unexpected line {text[i]!r}')
        names.append(s)
    sys.exit('sounds.h: NUMSFX not found')


def table():
    lines = (SRC / 'sounds.c').read_text(encoding='latin-1').splitlines()
    first = next(i for i, l in enumerate(lines) if l.startswith('sfxinfo_t S_sfx[]'))
    rows = []
    pat = re.compile(r'\s*\{\s*"(\w+)"\s*,\s*(true|false)\s*,\s*(-?\d+)\s*,\s*(0|&S_sfx\[(sfx_\w+)\])\s*,'
                     r'\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*0\s*\}\s*,?\s*$')
    for i in range(first, len(lines)):
        if lines[i].startswith('};'):
            return rows, first + 1, i + 1
        m = pat.match(lines[i])
        if m:
            rows.append(dict(line=i + 1, name=m.group(1), sing=m.group(2) == 'true', prio=int(m.group(3)),
                             link=m.group(5), pitch=int(m.group(6)), volume=int(m.group(7))))
        elif '{' in lines[i] and lines[i].strip() != '{':
            sys.exit(f'sounds.c:{i + 1}: unparsed initialiser {lines[i]!r}')
    sys.exit('sounds.c: end of S_sfx not found')


def iroot(x, n):
    lo, hi = 0, 1 << (x.bit_length() // n + 1)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if mid ** n <= x: lo = mid
        else: hi = mid - 1
    return lo


def render_table():
    enums, e0, e1 = enumerators()
    rows, t0, t1 = table()
    if len(enums) != 109 or len(rows) != 109:
        sys.exit(f'expected 109 enumerators and 109 rows, found {len(enums)} and {len(rows)}')
    linked = 0
    out = ['// @generated by tools/reference/m5c_sounds_table.py from linuxdoom-1.10/sounds.c and sounds.h;',
           '// do not edit (check with `python3 tools/reference/m5c_sounds_table.py --check`).',
           f'// S_sfx: sounds.c:{t0}-{t1}; sfxenum_t: sounds.h:{e0}-{e1} (sfx_None = 0, NUMSFX = 109).',
           '',
           '/// `S_sfx[]` (sounds.c:114-227) in `sfxenum_t` order (sounds.h:177-289): index = sfx number.',
           'pub static S_SFX: [SfxInfo; NUMSFX] = [']
    for i, (e, r) in enumerate(zip(enums, rows)):
        if e.lower() != 'sfx_' + r['name']:   # sfx_None pairs with "none" (sounds.c:117)
            sys.exit(f'enumerator {e} (id {i}) does not pair with table row "{r["name"]}" at sounds.c:{r["line"]}')
        link = 'None'
        if r['link']:
            linked += 1
            if r['link'] not in enums: sys.exit(f'sounds.c:{r["line"]}: link to unknown {r["link"]}')
            link = f'Some({enums.index(r["link"])})'
        out.append(f'    SfxInfo {{ name: "{r["name"]}", singularity: {str(r["sing"]).lower()}, priority: {r["prio"]}, '
                   f'link: {link}, link_pitch: {r["pitch"]}, link_volume: {r["volume"]} }}, // {i} {e}, sounds.c:{r["line"]}')
    if linked != 1: sys.exit(f'expected exactly one linked entry, found {linked}')
    out.append('];')
    return '\n'.join(out) + '\n'


def steptable():
    return [iroot(1 << (1024 + p - 128), 64) for p in range(256)]


def step_digest_error(step):
    """None when the table's SHA-256 is the genuine one, else the message."""
    digest = hashlib.sha256(struct.pack('<256i', *step)).hexdigest()
    return None if digest == STEP_SHA256 else f'steptable digest {digest} differs from the genuine {STEP_SHA256}'


def render_step(step=None):
    step = steptable() if step is None else step
    err = step_digest_error(step)
    if err: sys.exit(err)
    digest = STEP_SHA256
    out = ['// @generated by tools/reference/m5c_sounds_table.py; do not edit',
           '// (check with `python3 tools/reference/m5c_sounds_table.py --check`).',
           '// steptable[p] = (int)(pow(2.0, (p-128)/64.0) * 65536.0) (i_sound.c:404, 414-415), generated exactly as the',
           '// integer 64th root of 2^(1024 + p - 128); SHA-256 of the little-endian int32 array:',
           f'// {digest} (the genuine table, tests/reference/m5c_mixer_results.json).',
           '',
           '/// `steptable[256]` (i_sound.c:144, filled by `I_SetChannels`, i_sound.c:404, 414-415): pitch to',
           '/// 16.16 step.',
           'pub static STEPTABLE: [u32; 256] = [']
    for k in range(0, 256, 8):
        out.append('    ' + ' '.join(f'{v},' for v in step[k:k + 8]))
    out.append('];')
    return '\n'.join(out) + '\n'


def compare(want, read):
    """The --check comparison: for each (path, text) of `want`, `read(path)` (the file's text, or
    None when absent) against the text. Returns [(path, 'matches' | 'DIFFERS')]."""
    return [(path, 'matches' if read(path) == text else 'DIFFERS') for path, text in want.items()]


def check(want):
    results = compare(want, lambda p: p.read_text() if p.exists() else None)
    for path, verdict in results:
        print(f'{path.relative_to(ROOT)}: {verdict}')
    print(f'S_sfx: 109 entries, 1 link; steptable: 256 entries, SHA-256 {STEP_SHA256}')
    return 1 if any(v != 'matches' for _, v in results) else 0


def self_test(want):
    """Planted faults through the real comparison and the real digest check."""
    ok, total = 0, 0
    for path, text in want.items():
        committed = path.read_text() if path.exists() else None
        for name, have, expect in (
            ('the committed file', committed, 'matches'),
            ('one changed byte', committed.replace('64', '65', 1) if committed else None, 'DIFFERS'),
            ('the file missing', None, 'DIFFERS'),
        ):
            got = dict(compare({path: text}, lambda p, h=have: h))[path]
            total += 1
            ok += got == expect
            print(f'self-test: {path.name}, {name}: {got} (want {expect})')
    step = steptable()
    planted = step[:]
    planted[112] += 1
    for name, table, want_err in (('the generated steptable', step, False), ('entry 112 plus one', planted, True)):
        err = step_digest_error(table) is not None
        total += 1
        ok += err == want_err
        print(f'self-test: digest of {name}: {"differs" if err else "genuine"} (want {"differs" if want_err else "genuine"})')
    print(f'self-test: {ok} of {total}')
    return 0 if ok == total else 1


def main(argv):
    if argv and argv[0] in ('-h', '--help'):
        print(__doc__); return 0
    modes = set(argv)
    if len(modes) != len(argv) or not modes <= {'--check', '--self-test'}:
        sys.stderr.write('usage: m5c_sounds_table.py [--check] [--self-test]\n'); return 1
    want = {OUT_TABLE: render_table(), OUT_STEP: render_step()}
    if modes:
        code = 0
        if '--check' in modes: code |= check(want)
        if '--self-test' in modes: code |= self_test(want)
        return code
    for path, text in want.items():
        path.write_text(text)
        print(f'wrote {path.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
