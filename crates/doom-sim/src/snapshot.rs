fn weapon_bytes(b: &mut Vec<u8>, event: &crate::WeaponEvent) {
    use crate::WeaponEvent::*;
    match event {
        Entered {
            slot,
            position,
            state,
        } => {
            b.extend([0, *slot, *position]);
            b.extend(state.0.to_le_bytes());
        }
        Action {
            slot,
            position,
            action,
        } => {
            b.extend([1, *slot, *position]);
            b.extend(action.0.to_le_bytes());
        }
        Ammo {
            slot,
            ammo,
            before,
            after,
        } => {
            b.extend([2, *slot, *ammo]);
            b.extend(before.to_le_bytes());
            b.extend(after.to_le_bytes());
        }
        Light { slot, value } => {
            b.extend([3, *slot]);
            b.extend(value.to_le_bytes());
        }
        Fire {
            slot,
            weapon,
            refire,
        } => {
            b.extend([4, *slot, *weapon as u8]);
            b.extend(refire.to_le_bytes());
        }
        Bullet {
            actor,
            angle,
            slope,
            damage,
        } => {
            b.push(5);
            b.extend(id(*actor));
            b.extend(angle.to_le_bytes());
            b.extend(slope.bits().to_le_bytes());
            b.extend(damage.to_le_bytes());
        }
        Noise {
            sector,
            blocks,
            target,
        } => {
            b.push(6);
            b.extend(sector.to_le_bytes());
            b.push(*blocks);
            b.extend(id(*target));
        }
        Initialized { slot, actor } => {
            b.extend([7, *slot]);
            b.extend(id(*actor));
        }
        Random { kind, value } => b.extend([8, *kind, *value]),
    }
}
/// Source aim evidence, reusing the combat trace representation.
pub(crate) fn aim_bytes(b: &mut Vec<u8>, a: &crate::AimResult) {
    let result = crate::AttackResult {
        trace: a.trace.clone(),
        hit: a.stopped,
        position: None,
        traversed: a.traversed,
        effect: None,
        damage: None,
    };
    combat_bytes(
        b,
        &crate::CombatEvent::Trace {
            result: Box::new(result),
        },
    );
    b.extend(optional_id(a.target));
    for v in [a.slope, a.window[0], a.window[1]] {
        b.extend(v.bits().to_le_bytes());
    }
}

